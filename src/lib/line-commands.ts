/** คำสั่งเมนูของผู้เช่าใน LINE — ต้องเป็น "คำล้วนๆ" ไม่ใช่แค่ขึ้นต้น */
const MENU_CMD_RE =
  /^(บิล|ยอดค้าง|ค้างชำระ|พัสดุ|ห้อง|ข้อมูล|ชำระ|ชำระเงิน|จ่ายเงิน|โอน|ติดต่อ|ผู้ดูแล|เจ้าของ)$/;

/**
 * ระหว่างที่ผู้เช่าอยู่ในสถานะ "รอพิมพ์รายละเอียดแจ้งซ่อม" (line_state=maintenance)
 * ข้อความถัดไปถือเป็น "รายละเอียดงานซ่อม" เสมอ ยกเว้น
 *   - เป็นคำสั่งเมนูล้วนๆ เช่น "ห้อง", "บิล" → ผู้เช่าเปลี่ยนใจไปดูเมนูอื่น
 *   - ขึ้นต้นด้วย "แจ้งซ่อม" → เริ่มแจ้งซ่อมรายการใหม่
 *
 * เดิม regex ใช้ ^prefix ทำให้ "ห้องน้ำรั่ว" ถูกตีเป็นคำสั่ง "ห้อง"
 * แล้วงานซ่อมไม่ถูกสร้าง (ผู้เช่านึกว่าแจ้งแล้วแต่ระบบเงียบ)
 */
export function isMaintenanceDetail(text: string): boolean {
  const t = text.trim();
  if (!t) return false;
  if (t.startsWith("แจ้งซ่อม")) return false;
  return !MENU_CMD_RE.test(t);
}
